// ValidateStructureStage1 checks length, formatting, character constraints, and polynomial checksum.
func ValidateStructureStage1(input string) bool {
	if len(input) != ExpectedKeyLength {
		return false
	}

	// Must begin with "SV-"
	if input[0] != 'S' || input[1] != 'V' || input[2] != '-' {
		return false
	}

	// Hyphen separators at indices 7, 12, 17, 22, 27
	delims := []int{7, 12, 17, 22, 27}
	for _, idx := range delims {
		if input[idx] != '-' {
			return false
		}
	}

	// Check hex characters
	hexIndices := []int{
		3, 4, 5, 6,
		8, 9, 10, 11,
		13, 14, 15, 16,
		18, 19, 20, 21,
		23, 24, 25, 26,
		28, 29, 30, 31,
	}

	var hexChars []byte
	for _, idx := range hexIndices {
		ch := input[idx]
		isDigit := ch >= '0' && ch <= '9'
		isUpperHex := ch >= 'A' && ch <= 'F'
		if !isDigit && !isUpperHex {
			return false
		}
		hexChars = append(hexChars, ch)
	}

	// Positional polynomial checksum
	csum := uint32(0x5A17F00D)
	for i, ch := range hexChars {
		csum = (csum*31 + uint32(ch)*17 + uint32(i*13)) & 0xFFFFFFFF
	}

	return csum == Stage1ExpectedChecksum
}

// TransformStage2 applies byte permutation, masking, and circular rotation.
func TransformStage2(input []byte) [32]byte {
	var out [32]byte
	for i := 0; i < 32; i++ {
		orig := input[Permutation[i]]
		x := orig ^ MaskK[i]
		shift := byte((i % 7) + 1)
		rot := (x << shift) | (x >> (8 - shift))
		out[i] = rot + AddC[i]
	}
	return out
}
