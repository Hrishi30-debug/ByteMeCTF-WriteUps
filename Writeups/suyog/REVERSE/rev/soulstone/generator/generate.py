"""
SoulStone Challenge Generator
Calculates target resonance tag, derives keys, encrypts flag with ChaCha20 and HMAC-SHA256,
and outputs C header constants.
"""

import struct
import hashlib
import hmac

SACRIFICE = "GAMORA"
TARGET_TOKEN = 0xA73D91
TOKEN_STR = f"{TARGET_TOKEN:06X}"
OFFERING = f"SOUL{{{SACRIFICE}:{TOKEN_STR}}}"
FLAG = "OWASP{a_s0ul_f0r_a_s0ul_v0rm1r_cl1ff_7c8d9e2a}"
ALTAR_SALT = "VORMIR_SOUL_TITHE_2026"

def soul_resonance(sacrifice: str, token: int) -> int:
    h = 0x5A17F00D
    for ch in sacrifice.encode("ascii"):
        h = ((h * 31 + ch) ^ 0x9E3779B9) & 0xFFFFFFFF
    
    state = (h ^ token) & 0xFFFFFFFF
    for _ in range(4):
        state = ((state ^ (state >> 15)) * 0x85EBCA6B) & 0xFFFFFFFF
        state = ((state ^ (state >> 13)) * 0xC2B2AE35) & 0xFFFFFFFF
        state = (state ^ (state >> 16)) & 0xFFFFFFFF
        state = (state + token) & 0xFFFFFFFF
    return state

# ChaCha20 pure python implementation for cross-verification
def rotl32(v, c):
    return ((v << c) & 0xFFFFFFFF) | (v >> (32 - c))

def chacha20_quarter_round(a, b, c, d, state):
    state[a] = (state[a] + state[b]) & 0xFFFFFFFF
    state[d] = rotl32(state[d] ^ state[a], 16)
    state[c] = (state[c] + state[d]) & 0xFFFFFFFF
    state[b] = rotl32(state[b] ^ state[c], 12)
    state[a] = (state[a] + state[b]) & 0xFFFFFFFF
    state[d] = rotl32(state[d] ^ state[a], 8)
    state[c] = (state[c] + state[d]) & 0xFFFFFFFF
    state[b] = rotl32(state[b] ^ state[c], 7)

def chacha20_block(key, counter, nonce):
    # constants "expand 32-byte k"
    state = [
        0x61707865, 0x3320646e, 0x79622d32, 0x6b206574,
        *struct.unpack("<8I", key),
        counter,
        *struct.unpack("<3I", nonce)
    ]
    working = list(state)
    for _ in range(10):
        # Column round
        chacha20_quarter_round(0, 4, 8, 12, working)
        chacha20_quarter_round(1, 5, 9, 13, working)
        chacha20_quarter_round(2, 6, 10, 14, working)
        chacha20_quarter_round(3, 7, 11, 15, working)
        # Diagonal round
        chacha20_quarter_round(0, 5, 10, 15, working)
        chacha20_quarter_round(1, 6, 11, 12, working)
        chacha20_quarter_round(2, 7, 8, 13, working)
        chacha20_quarter_round(3, 4, 9, 14, working)
    
    out = bytearray(64)
    for i in range(16):
        val = (working[i] + state[i]) & 0xFFFFFFFF
        out[i*4:(i+1)*4] = struct.pack("<I", val)
    return bytes(out)

def chacha20_xor(key, nonce, plaintext, counter=1):
    keystream = bytearray()
    needed_blocks = (len(plaintext) + 63) // 64
    for b in range(needed_blocks):
        keystream.extend(chacha20_block(key, counter + b, nonce))
    return bytes([p ^ k for p, k in zip(plaintext, keystream)])

def main():
    print("=== SoulStone CTF Challenge Generator ===")
    
    target_tag = soul_resonance(SACRIFICE, TARGET_TOKEN)
    print(f"[+] Sacrifice:           {SACRIFICE}")
    print(f"[+] Target Token:        0x{TARGET_TOKEN:06X} ({TARGET_TOKEN})")
    print(f"[+] Full Offering:       {OFFERING}")
    print(f"[+] Target Resonance Tag:0x{target_tag:08X}")
    print(f"[+] Flag:                {FLAG}")

    # Key derivation
    kdf_input = f"{SACRIFICE}:{TOKEN_STR}:{ALTAR_SALT}".encode("ascii")
    master_key = hashlib.sha256(kdf_input).digest()
    
    chacha_key = hashlib.sha256(master_key + b"::CIPHER_KEY").digest()
    chacha_nonce = hashlib.sha256(master_key + b"::NONCE").digest()[:12]
    hmac_key = hashlib.sha256(master_key + b"::HMAC_KEY").digest()

    print(f"[+] ChaCha20 Key:        {chacha_key.hex()}")
    print(f"[+] ChaCha20 Nonce:      {chacha_nonce.hex()}")

    # Encrypt flag
    flag_bytes = FLAG.encode("utf-8")
    ciphertext = chacha20_xor(chacha_key, chacha_nonce, flag_bytes, counter=1)
    
    # Compute HMAC-SHA256 over ciphertext
    tag = hmac.new(hmac_key, ciphertext, hashlib.sha256).digest()
    print(f"[+] Ciphertext ({len(ciphertext)} bytes): {ciphertext.hex()}")
    print(f"[+] HMAC-SHA256 Tag:    {tag.hex()}")

    # Verify decryption
    decrypted = chacha20_xor(chacha_key, chacha_nonce, ciphertext, counter=1).decode("utf-8")
    assert decrypted == FLAG, "Decryption verification failed!"
    print("[+] Decryption test passed!")

